		public void Process(Image<BGR32> srcImg, Image<Gray> destImg)
		{
			int srcIdx = 0;
			byte[] src = srcImg.Data;
			byte[] dst = destImg.Data;
			for (int dstIdx = 0; dstIdx < destImg.DataLength; dstIdx++)
			{
				int idx = ((src[srcIdx] & 0xf0) << 4) + (src[srcIdx + 1] & 0xf0) + (src[srcIdx + 2] >> 4);
				dst[dstIdx] = histData[idx];
				srcIdx += 4;
			}
		}

